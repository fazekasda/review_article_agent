"""Error vocabulary for the durable local project foundation.

Every error carries an **actionable** message: what failed, which stable
identifier (project ID, schema version, path) was involved, and what the caller
or user should do next. Messages must never embed raw SQL, credentials, or
source text — the storage layer therefore wraps ``sqlite3.Error`` with a
human-readable summary and chains the original exception via ``raise ... from``
for debugging only.

Hierarchy::

    ReviewAgentError
    ├── StoreError                     # storage/schema problems
    │   ├── SchemaVersionError
    │   │   └── UnsupportedSchemaVersion
    │   ├── MigrationError
    │   └── RegistryError
    │       └── LockError
    └── ProjectError                   # project identity / location problems
        ├── ProjectNotFound
        ├── InvalidProjectId
        ├── ProjectConflict
        ├── ProjectPathError
        └── NoActiveProject
"""

from __future__ import annotations


class ReviewAgentError(Exception):
    """Base class for every error raised by this package."""


# --------------------------------------------------------------------------- #
# Storage / schema
# --------------------------------------------------------------------------- #
class StoreError(ReviewAgentError):
    """A project store or registry could not be opened, migrated, or used."""


class SchemaVersionError(StoreError):
    """The on-disk schema version is not usable by this application version."""


class UnsupportedSchemaVersion(SchemaVersionError):
    """The store/registry was written by a newer, unsupported schema version.

    Step 02 must *fail clearly* rather than read or downgrade a future schema
    (``docs/implementation/02-project-foundation.md`` line 21). Upgrading the
    application is the only safe remedy.
    """

    def __init__(self, *, label: str, found: int, supported: int) -> None:
        super().__init__(
            f"{label} schema version {found} is newer than this application "
            f"supports (max {supported}); upgrade review_article_agent instead "
            f"of opening it with an older version."
        )
        self.label = label
        self.found = found
        self.supported = supported


class MigrationError(StoreError):
    """A schema migration failed and was rolled back."""

    def __init__(self, *, label: str, target: int, reason: str) -> None:
        super().__init__(
            f"{label} migration to schema version {target} failed and was "
            f"rolled back ({reason}); no partial schema was left in place."
        )
        self.label = label
        self.target = target
        self.reason = reason


class RegistryError(StoreError):
    """The application-level registry could not be read or updated."""


class LockError(RegistryError):
    """The registry lock could not be acquired."""


# --------------------------------------------------------------------------- #
# Project identity / location
# --------------------------------------------------------------------------- #
class ProjectError(ReviewAgentError):
    """A project identity, location, or lifecycle operation failed."""


class ProjectNotFound(ProjectError):
    """No project with the requested stable ID is registered."""

    def __init__(self, project_id: str) -> None:
        super().__init__(
            f"no project is registered with id {project_id!r}; run "
            f"`list` to see registered projects or `create`/`register` to add it."
        )
        self.project_id = project_id


class InvalidProjectId(ProjectError):
    """A project ID is not a valid application project ID.

    Project IDs are generated by the application and are safe as opaque
    identifiers; a caller-supplied ID that does not match the expected shape is
    rejected before it reaches the registry or the filesystem (this blocks
    traversal-style values).
    """

    def __init__(self, project_id: object, *, expected: str) -> None:
        super().__init__(
            f"{project_id!r} is not a valid project id (expected {expected})."
        )
        self.project_id = project_id


class ProjectConflict(ProjectError):
    """A create/register request conflicts with existing registered state.

    The operation is **not** retried silently: a genuinely duplicated request
    (same location, same identity) is idempotent, but a divergent request is
    surfaced so the caller can decide.
    """


class ProjectPathError(ProjectError):
    """A project's on-disk store is missing, mismatched, or unsafe.

    Raised for: a missing store, an ID/location mismatch, a symlinked store,
    an unregistered app-owned directory that must be registered explicitly, or
    a stale duplicate location. Never resolved by guessing.
    """


class NoActiveProject(ProjectError):
    """No project is currently selected."""

    def __init__(self) -> None:
        super().__init__(
            "no active project is selected; run `select <project_id>` first."
        )
